#!/usr/bin/env python3
"""Subset tabi's web fonts for idle-ti.me.

tabi ships Inter and Source Serif with every script they support (Cyrillic,
Greek, Vietnamese...): 397 KB of the ~450 KB an article weighed. This site is
written in English with some French, so this script keeps Latin, Latin
Extended-A and the punctuation, arrows and maths signs the posts use. It writes
two kinds of files under static/, which Zola copies over the theme's own:

- static/fonts/<name>.woff2: same file names as the theme, so tabi's
  @font-face rules pick them up unchanged.
- static/custom_subset.css: the 'Inter Subset' font tabi loads first for the
  header (`custom_subset = true`), cut to the characters of the site title and
  menu, so the header never flashes in a fallback font. The theme's default
  file is cut for tabi's demo site and lacks d, m, u, y, '-' and '.'.

Run it again after changing the title or the menu in config.toml, or after a
tabi update that changes the fonts. It then lists the characters used in
public/ (run `zola build` first) that the subsets dropped but the original
fonts had: add those to UNICODES, or they render in a fallback font.

Requires: pip install fonttools brotli
Usage:    python3 scripts/subset_fonts.py [build-dir]   (default: public/)
"""

import base64
import html
import io
import re
import sys
import tomllib
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
THEME_FONTS = ROOT / "themes/tabi/static/fonts"
OUT_FONTS = ROOT / "static/fonts"
OUT_HEADER_CSS = ROOT / "static/custom_subset.css"
PUBLIC = ROOT / "public"

# Cascadia Code is absent: tabi already ships it cut to ASCII (13 KB).
FONTS = ["Inter4.woff2", "SourceSerif4Variable-Roman.ttf.woff2"]

UNICODES = [
    (0x0020, 0x007E),  # Basic Latin
    (0x00A0, 0x017F),  # Latin-1 Supplement, Latin Extended-A
    (0x0192, 0x0192),  # ƒ
    (0x02C6, 0x02C6),  # ˆ
    (0x02DA, 0x02DA),  # ˚
    (0x02DC, 0x02DC),  # ˜
    (0x2000, 0x206F),  # General Punctuation: dashes, quotes, bullet, ellipsis
    (0x20AC, 0x20AC),  # €
    (0x2122, 0x2122),  # ™
    (0x2190, 0x21FF),  # Arrows: ← → ↩
    (0x2212, 0x2212),  # − minus
    (0x2215, 0x2215),  # ∕
    (0x221E, 0x221E),  # ∞
    (0x2248, 0x2248),  # ≈
    (0x2260, 0x2260),  # ≠
    (0x2264, 0x2265),  # ≤ ≥
    (0x27F6, 0x27F6),  # ⟶
]


def codepoints():
    return {c for lo, hi in UNICODES for c in range(lo, hi + 1)}


def subset_font(src, unicodes):
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    options.name_IDs = ["*"]  # keep the copyright and licence (SIL OFL)
    font = subset.load_font(str(src), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=unicodes)
    subsetter.subset(font)
    buf = io.BytesIO()
    subset.save_font(font, buf, options)
    return buf.getvalue()


def header_text():
    config = tomllib.loads((ROOT / "config.toml").read_text())
    names = [item["name"] for item in config.get("extra", {}).get("menu", [])]
    return config["title"] + " " + " ".join(names)


def used_characters(build_dir):
    """Characters of the built site's text, code blocks included."""
    chars = set()
    for page in build_dir.rglob("*.html"):
        text = page.read_text(encoding="utf-8")
        text = re.sub(r"<(script|style)\b.*?</\1>", "", text, flags=re.S)
        chars |= set(html.unescape(re.sub(r"<[^>]+>", " ", text)))
    return chars


def main():
    OUT_FONTS.mkdir(parents=True, exist_ok=True)
    wanted = codepoints()

    for name in FONTS:
        src = THEME_FONTS / name
        data = subset_font(src, wanted)
        (OUT_FONTS / name).write_bytes(data)
        print(f"{name}: {src.stat().st_size // 1024} KB -> {len(data) // 1024} KB")

    text = header_text()
    data = subset_font(THEME_FONTS / "Inter4.woff2", {ord(c) for c in text})
    b64 = base64.b64encode(data).decode("ascii")
    OUT_HEADER_CSS.write_text(
        "/* Generated by scripts/subset_fonts.py from the site title and menu:"
        f" {''.join(sorted(set(text)))!r} */\n"
        '@font-face{font-family:"Inter Subset";'
        f"src:url(data:application/font-woff2;base64,{b64});}}\n"
    )
    print(f"custom_subset.css: {OUT_HEADER_CSS.stat().st_size // 1024} KB")

    build_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else PUBLIC
    if not build_dir.is_dir():
        print(f"{build_dir} not found: run `zola build` first to check coverage.")
        return 0
    used = used_characters(build_dir)
    dropped = set()
    for name in FONTS:
        original = set(TTFont(THEME_FONTS / name).getBestCmap())
        dropped |= {chr(c) for c in original - wanted}
    missing = sorted(used & dropped)
    if missing:
        listing = " ".join(f"{c} U+{ord(c):04X}" for c in missing)
        print(f"Used in {build_dir} but dropped from the subsets: {listing}")
        return 1
    print(f"Coverage: every character in {build_dir} that the fonts had is kept.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
